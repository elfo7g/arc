function mergeTranslation(base = {}, overrides = {}) {
  const safeBase = base && typeof base === "object" ? base : {};
  const safeOverrides = overrides && typeof overrides === "object" ? overrides : {};
  const output = { ...safeBase };
  for (const [key, value] of Object.entries(safeOverrides)) {
    const baseValue = safeBase[key];
    const shouldMerge =
      value &&
      typeof value === "object" &&
      !Array.isArray(value) &&
      baseValue &&
      typeof baseValue === "object" &&
      !Array.isArray(baseValue);
    output[key] = shouldMerge ? mergeTranslation(baseValue, value) : value;
  }
  return output;
}

