// ---- Locale-aware date helpers (replace the old hardcoded 月/日 formatting) ----

export function formatMonthDay(dateKey, lang = "ja") {
  if (!dateKey) return "";
  const date = new Date(`${dateKey}T00:00:00`);
  if (Number.isNaN(date.getTime())) return "";
  return new Intl.DateTimeFormat(LOCALE_TAGS[lang] || "ja-JP", { month: "long", day: "numeric" }).format(date);
}

export function formatWeekday(dateKey, lang = "ja") {
  if (!dateKey) return "";
  const date = new Date(`${dateKey}T00:00:00`);
  if (Number.isNaN(date.getTime())) return "";
  return new Intl.DateTimeFormat(LOCALE_TAGS[lang] || "ja-JP", { weekday: "short" }).format(date);
}

export function formatMonthLabel(monthKey, lang = "ja") {
  const [year, mon] = String(monthKey).split("-");
  if (!year || !mon) return translate(lang, "chapter.unknownPeriod");
  const date = new Date(Number(year), Number(mon) - 1, 1);
  return new Intl.DateTimeFormat(LOCALE_TAGS[lang] || "ja-JP", { year: "numeric", month: "long" }).format(date);
}

export function formatQuestSince(dateKey, lang = "ja") {
  const date = new Date(`${dateKey}T00:00:00`);
  if (Number.isNaN(date.getTime())) return "";
  const monthDay = new Intl.DateTimeFormat(LOCALE_TAGS[lang] || "ja-JP", { month: "long", day: "numeric" }).format(date);
  return lang === "ja" ? `${monthDay}から` : `${translate(lang, "quests.sinceSuffix")}${monthDay}`;
}

export function formatQuestDuration(dateKey, lang = "ja", now = new Date()) {
  const start = new Date(`${dateKey}T00:00:00`);
  if (Number.isNaN(start.getTime())) return "";
  const days = Math.max(0, Math.floor((now - start) / 86400000));
  if (days < 7) return translate(lang, "quests.justStarted");
  if (days < 60) return `${Math.floor(days / 7)}${translate(lang, "quests.weeksSuffix")}`;
  if (days < 365) return `${Math.floor(days / 30)}${translate(lang, "quests.monthsSuffix")}`;
  const years = Math.floor(days / 365);
  const months = Math.floor((days % 365) / 30);
  const yearsSuffix = translate(lang, "quests.yearsSuffix");
  const monthsSuffix = translate(lang, "quests.monthsSuffix");
  const joiner = translate(lang, "quests.partsJoiner");
  return months ? `${years}${yearsSuffix}${joiner}${months}${monthsSuffix}` : `${years}${yearsSuffix}`;
}

export function formatNotificationTimestamp(value, lang = "ja") {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  const now = new Date();
  const sameDay = date.toDateString() === now.toDateString();
  if (sameDay) {
    const time = new Intl.DateTimeFormat(LOCALE_TAGS[lang] || "ja-JP", { hour: "2-digit", minute: "2-digit", hour12: false }).format(date);
    return `${translate(lang, "notifications.todayPrefix")} ${time}`;
  }
  return new Intl.DateTimeFormat(LOCALE_TAGS[lang] || "ja-JP", { month: "long", day: "numeric" }).format(date);
}
