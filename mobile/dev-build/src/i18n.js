function getPath(obj, path) {
  return path.split(".").reduce((acc, key) => (acc == null ? acc : acc[key]), obj);
}

// Looks up a dot-path key (e.g. "settings.app.languageLabel") in the given
// language, falling back to Japanese and finally the key itself so a missing
// translation never renders as a crash or blank text.
export function translate(lang, key, ...args) {
  const dict = translations[lang] || translations.ja;
  let value = getPath(dict, key);
  if (value === undefined) value = getPath(translations.ja, key);
  if (typeof value === "function") return value(...args);
  if (value === undefined) return key;
  return value;
}

export const LanguageContext = createContext("ja");

